// Regenerates the vendored file-icon subset from material-icon-theme (MIT).
//
//   npm pack material-icon-theme@5.39.0 && tar -xzf material-icon-theme-5.39.0.tgz
//   node scripts/gen-file-icons.mjs path/to/package
//
// Only the icons reached by the seed names below are copied, plus every
// filename / extension / folder name / language id upstream maps to them.
// Never run anything from the package itself: it is read as data.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync, existsSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = process.argv[2];
if (!pkgDir) throw new Error("usage: node scripts/gen-file-icons.mjs <material-icon-theme package dir>");
const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(repo, "src/assets/file-icons");
const m = JSON.parse(readFileSync(join(pkgDir, "dist/material-icons.json"), "utf8"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

const FILE_SEEDS = [
  "package.json", "package-lock.json", "tsconfig.json", "jsconfig.json", "cargo.toml", "cargo.lock",
  "poetry.lock", "pyproject.toml", "requirements.txt", "pnpm-lock.yaml", "yarn.lock", "bun.lockb",
  "dockerfile", "docker-compose.yml", ".gitignore", ".gitattributes", "readme.md", "license",
  "changelog.md", "contributing.md", "makefile", ".editorconfig", ".prettierrc", ".eslintrc", ".npmrc",
  "vite.config.ts", "vitest.config.ts", "tailwind.config.ts", "tauri.conf.json", ".env", "go.mod",
  "build.gradle", "pom.xml", "deno.json", "vercel.json", "gemfile", "composer.json", "babel.config.js",
  "webpack.config.js", "postcss.config.js", ".nvmrc", "cmakelists.txt", "claude.md",
];
const EXT_SEEDS = [
  "ts", "d.ts", "test.ts", "spec.ts", "test.tsx", "spec.tsx", "test.js", "tsx", "js", "jsx", "mjs",
  "rs", "py", "ipynb", "go", "java", "kt", "swift", "rb", "php", "cs", "lua", "dart", "vue", "svelte",
  "c", "h", "cpp", "hpp", "html", "css", "scss", "less", "json", "yaml", "toml", "ini", "xml", "csv",
  "md", "mdx", "txt", "log", "pdf", "sh", "ps1", "bat", "sql", "db", "prisma", "graphql", "png", "svg",
  "mp3", "mp4", "zip", "exe", "dll", "wasm", "ttf", "pem", "key", "lock", "r", "scala", "hs", "ex",
  "zig", "jl", "pl", "astro", "tf", "nix", "proto", "diff", "http", "xlsx", "docx",
];
const FOLDER_SEEDS = [
  "src", "node_modules", ".git", ".github", ".vscode", "public", "assets", "tests", "docs", "target",
  "venv", "dist", "components", "lib", "scripts", "config", "images", "styles", "hooks", "store",
  "utils", "types", "api", "server", "test", "src-tauri", "release-notes",
];

const defs = m.iconDefinitions;
const ids = new Set([m.file, m.folder, m.folderExpanded]);
const add = (id, what) => (id ? ids.add(id) : console.warn("no upstream icon for", what));
for (const n of FILE_SEEDS) add(m.fileNames[n] ?? m.fileExtensions[n.split(".").pop()], n);
for (const e of EXT_SEEDS) add(m.fileExtensions[e] ?? m.languageIds[e], e);
for (const f of FOLDER_SEEDS) {
  add(m.folderNames[f], f);
  if (m.folderNames[f]) add(m.folderNamesExpanded[f], f + " (open)");
}
// Light-background variants of the chosen icons.
for (const id of [...ids]) if (defs[id + "_light"]) ids.add(id + "_light");

const keep = (table, simple) =>
  Object.fromEntries(
    Object.entries(table ?? {})
      .filter(([k, id]) => ids.has(id) && !k.includes("/") && (!simple || !/^[_.]/.test(k) || FOLDER_SEEDS.includes(k)))
      .map(([k, id]) => [k.toLowerCase(), id])
  );
const light = {};
for (const t of ["fileNames", "fileExtensions", "languageIds"]) Object.assign(light, m.light?.[t] ?? {});
const lightIds = Object.fromEntries(
  Object.values(light).filter((id) => ids.has(id)).map((id) => [id.replace(/_light$/, ""), id])
);

const map = {
  file: m.file,
  folder: m.folder,
  folderOpen: m.folderExpanded,
  fileNames: keep(m.fileNames),
  fileExtensions: keep(m.fileExtensions),
  languageIds: keep(m.languageIds),
  // Upstream lists ".src", "_src", "__src__" etc.; plain names cover what people actually use.
  folderNames: keep(m.folderNames, true),
  folderNamesOpen: keep(m.folderNamesExpanded, true),
  light: lightIds,
};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
let bytes = 0;
for (const id of ids) {
  const src = join(pkgDir, "dist", defs[id].iconPath);
  if (!existsSync(src)) throw new Error("missing svg " + src);
  copyFileSync(src, join(outDir, id + ".svg"));
  bytes += statSync(src).size;
}
copyFileSync(join(pkgDir, "LICENSE"), join(outDir, "LICENSE"));
writeFileSync(
  join(repo, "src/lib/fileIconMap.ts"),
  `// Generated by scripts/gen-file-icons.mjs from material-icon-theme@${version} (MIT). Do not edit.\n` +
    `type Table = Record<string, string>;\n` +
    `export const FILE_ICON_MAP: {\n` +
    `  file: string; folder: string; folderOpen: string; light: Table;\n` +
    `  fileNames: Table; fileExtensions: Table; languageIds: Table; folderNames: Table; folderNamesOpen: Table;\n` +
    `} = ${JSON.stringify(map, null, 1)};\n`
);
console.log(`${ids.size} icons, ${(bytes / 1024).toFixed(1)} KB`);
